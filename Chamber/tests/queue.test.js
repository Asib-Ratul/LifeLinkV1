import {test, before, after} from 'node:test';
import assert from 'node:assert/strict';
import {spawn} from 'node:child_process';
import {mkdtempSync,rmSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
const temp=mkdtempSync(join(tmpdir(),'chamber-test-'));
const port=33000+Math.floor(Math.random()*10000),base='http://127.0.0.1:'+port;
let server,owner='',other='',staff='',clinicId,slug,visit,token;
async function request(path,data,cookie='',origin){
 const r=await fetch(base+'/api/'+path,{method:data?'POST':'GET',headers:{...(data?{'Content-Type':'application/json'}:{}),...(cookie?{cookie}:{}),...(origin?{origin}:{})},body:data?JSON.stringify(data):undefined});
 return {status:r.status,data:await r.json(),cookie:r.headers.get('set-cookie')?.split(';')[0]};
}
before(async()=>{
 server=spawn(process.execPath,['src/server.js'],{env:{...process.env,PORT:String(port),HOST:'127.0.0.1',DATABASE_PATH:join(temp,'test.sqlite'),NODE_ENV:'test'},stdio:['ignore','pipe','pipe']});
 await new Promise((resolve,reject)=>{const t=setTimeout(()=>reject(new Error('Server did not start')),10000);server.stdout.on('data',d=>{if(d.toString().includes('Chamber is ready')){clearTimeout(t);resolve();}});server.once('exit',code=>reject(new Error('Server exited: '+code)));});
});
after(async()=>{if(server){server.kill();await new Promise(resolve=>server.once('exit',resolve));}rmSync(temp,{recursive:true,force:true});});
test('complete queue flow with clinic separation and public privacy',async()=>{
 let r=await request('workspace');assert.equal(r.status,401);
 r=await request('register',{name:'Owner One',clinic:'Test Clinic',doctor:'Dr Example',email:'owner@example.test',password:'test-password-long'});
 assert.equal(r.status,200);owner=r.cookie;assert.match(owner,/chamber_session=/);
 r=await request('workspace',null,owner);assert.equal(r.data.user.role,'owner');slug=r.data.clinic.slug;clinicId=r.data.clinic.id;
 r=await request('register',{name:'Owner Two',clinic:'Other Clinic',doctor:'Dr Other',email:'other@example.test',password:'test-password-long'});other=r.cookie;
 r=await request('clinics/'+slug,{name:'Patient One'});assert.equal(r.status,409);
 r=await request('queue',{action:'state',state:'open'},owner);assert.equal(r.status,200);
 r=await request('clinics/'+slug,{name:'Patient One'});assert.equal(r.status,200);token=r.data.token;assert.equal(r.data.serial,1);
 r=await request('track/'+token);assert.equal(r.data.serial,1);assert.equal(r.data.arrived,false);assert.ok(!JSON.stringify(r.data).includes('Patient One'));assert.ok(!JSON.stringify(r.data).includes(clinicId));
 r=await request('workspace',null,owner);visit=r.data.visits[0].id;
 r=await request('workspace',null,other);assert.equal(r.data.visits.length,0);
 r=await request('queue',{action:'arrive',id:visit},other);assert.equal(r.status,404);
 r=await request('queue',{action:'next'},owner);assert.equal(r.status,409);
 r=await request('track/'+token,{action:'arrive'});assert.equal(r.status,200);
 r=await request('visits',{name:'Patient Two'},owner);assert.equal(r.data.serial,2);
 r=await request('queue',{action:'next'},owner);assert.equal(r.status,200);
 r=await request('track/'+token);assert.equal(r.data.status,'serving');
 r=await request('queue',{action:'next'},owner);assert.equal(r.status,409);
 r=await request('track/'+token,{action:'cancel'});assert.equal(r.status,409);
 r=await request('queue',{action:'finish'},owner);assert.equal(r.status,200);
 r=await request('track/'+token);assert.equal(r.data.status,'done');
 r=await request('queue',{action:'state',state:'paused',notice:'Short break'},owner);assert.equal(r.status,200);
 r=await request('queue',{action:'next'},owner);assert.equal(r.status,409);
 r=await request('clinics/'+slug,{name:'Blocked Patient'});assert.equal(r.status,409);
 r=await request('queue',{action:'state',state:'open'},owner);
 r=await request('workspace',null,owner);const second=r.data.visits[1];
 r=await request('queue',{action:'skip',id:second.id},owner);assert.equal(r.status,200);
 r=await request('queue',{action:'restore',id:second.id},owner);assert.equal(r.status,200);
 r=await request('track/'+second.token,{action:'cancel'});assert.equal(r.status,200);
 r=await request('team',{name:'Doctor Staff',email:'staff@example.test',password:'staff-password-long',role:'doctor'},owner);assert.equal(r.status,200);
 r=await request('login',{email:'staff@example.test',password:'staff-password-long'});staff=r.cookie;assert.equal(r.status,200);
 r=await request('team',{name:'Not allowed'},staff);assert.equal(r.status,403);
 r=await request('visits',{name:'Not allowed'},staff);assert.equal(r.status,403);
 r=await request('settings',{},staff);assert.equal(r.status,403);
 r=await request('queue',{action:'state',state:'open'},owner,'https://untrusted.example');assert.equal(r.status,403);
 r=await request('settings',{name:'Test Clinic',doctor:'Dr Example',minutes:10,capacity:1,timezone:'Asia/Dhaka'},owner);assert.equal(r.status,200);
 r=await request('clinics/'+slug,{name:'Over capacity'});assert.equal(r.status,409);
 r=await request('workspace',null,owner);const member=r.data.team.find(x=>x.role==='doctor');
 r=await request('team/remove',{id:member.id},other);assert.equal(r.status,404);
 r=await request('team/remove',{id:member.id},owner);assert.equal(r.status,200);
 r=await request('workspace',null,staff);assert.equal(r.status,401);
 const previous=owner;
 r=await request('password',{current:'test-password-long',password:'changed-password-long'},owner);assert.equal(r.status,200);owner=r.cookie;
 r=await request('workspace',null,previous);assert.equal(r.status,401);
 r=await request('workspace',null,owner);assert.equal(r.status,200);
 r=await request('logout',{},owner);assert.equal(r.status,200);
 r=await request('workspace',null,owner);assert.equal(r.status,401);
 r=await request('login',{email:'owner@example.test',password:'wrong-password-long'});assert.equal(r.status,401);
 r=await request('track/not-a-token');assert.equal(r.status,404);
});
test('concurrent calls keep one active visit, including across midnight',async()=>{
 let r=await request('login',{email:'owner@example.test',password:'changed-password-long'});const cookie=r.cookie;
 await request('settings',{name:'Test Clinic',doctor:'Dr Example',minutes:10,capacity:20,timezone:'Asia/Dhaka'},cookie);
 await request('queue',{action:'state',state:'open'},cookie);
 await request('visits',{name:'Overnight Patient'},cookie);
 await request('visits',{name:'Following Patient'},cookie);
 const attempts=await Promise.all([request('queue',{action:'next'},cookie),request('queue',{action:'next'},cookie)]);
 assert.deepEqual(attempts.map(x=>x.status).sort(),[200,409]);
 const {DatabaseSync}=await import('node:sqlite');
 const connection=new DatabaseSync(join(temp,'test.sqlite'));
 connection.prepare("UPDATE visits SET day='2000-01-01' WHERE clinic_id=? AND status='serving'").run(clinicId);
 connection.close();
 r=await request('workspace',null,cookie);
 assert.equal(r.data.visits.filter(x=>x.status==='serving').length,1);
 r=await request('queue',{action:'finish'},cookie);assert.equal(r.status,200);
 r=await request('queue',{action:'next'},cookie);assert.equal(r.status,200);
});

